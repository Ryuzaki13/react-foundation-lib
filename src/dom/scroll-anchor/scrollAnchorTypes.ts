/** Одноразовая DOM-операция; host обязан завершить её после commit либо отменить при ошибке/unmount. */
export type CapturedScrollAnchor = Readonly<{
	/** true — прежний anchor ещё допустим и компенсация применена, в том числе при нулевом смещении. */
	restore: () => boolean;
	/** Освобождает временный стиль без изменения позиции прокрутки. Повторный вызов безопасен. */
	release: () => void;
}>;
