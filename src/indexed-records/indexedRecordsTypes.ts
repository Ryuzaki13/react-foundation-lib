/**
 * Упорядоченные записи и позиционный индекс без второй коллекции самих записей.
 *
 * Владелец исходного снимка сохраняет массив и записи неизменными после
 * построения: перестановка items или смена identity сделает индекс неверным.
 * readonly относится к контейнеру; неизменность полей T задаёт его владелец.
 */
export type IndexedRecords<T> = Readonly<{
	items: readonly T[];
	indexById: Readonly<Record<string, number>>;
}>;
